def _base(name):
    return re.sub(r"(시|군)$", "", name)


def station_for(sido, sigungu, stations):
    """stations: {지점번호: 관측소 이름}. 돌려주는 값: (지점번호, 짝지은 방식)"""
    if sido == "전남광주통합특별시":
        sido = "광주광역시" if sigungu in GWANGJU_GU else "전라남도"
    city = sigungu.split()[0]                       # '수원시 권선구' → '수원시'
    if (sido, city) in MANUAL:
        return MANUAL[(sido, city)], "인근 관측소(수동 지정)"
    by_name = {_base(n): k for k, n in stations.items()}
    if _base(city) in by_name:
        return by_name[_base(city)], "같은 이름 관측소"
    if sido in METRO:
        return METRO[sido], "같은 도시 관측소"
    return None, "미지정"
